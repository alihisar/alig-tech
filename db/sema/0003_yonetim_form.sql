-- 0003: yonetim paneli (yonetim/depo.py) ve iletisim formu (form/server.py) tablolari.
-- Mevcut adlar korunur. Tek istisna: yonetim zinciri de "denetim" adini tasiyordu (ayri SQLite dosyasi);
-- tek semada cakismasin diye yonetim_denetim olarak adlandirildi (tarama zinciri denetim kalir).
SET ROLE alig_owner;

CREATE TABLE alig.kullanici(
  ad            text PRIMARY KEY CHECK (ad <> ''),
  parola        text NOT NULL,
  totp          text NOT NULL,
  totp_sayac    bigint NOT NULL DEFAULT 0 CHECK (totp_sayac >= 0),
  olusturma_utc timestamptz NOT NULL
);

CREATE TABLE alig.oturum(
  kod_sha256     text PRIMARY KEY CHECK (kod_sha256 ~ '^[0-9a-f]{64}$'),
  ad             text NOT NULL REFERENCES alig.kullanici(ad) ON DELETE CASCADE,
  csrf           text NOT NULL,
  olusturma_utc  timestamptz NOT NULL,
  son_erisim_utc timestamptz NOT NULL
);
CREATE INDEX oturum_ad ON alig.oturum(ad);

CREATE TABLE alig.giris_denemesi(
  id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  anahtar   text NOT NULL,
  zaman_utc timestamptz NOT NULL
);
CREATE INDEX giris_anahtar ON alig.giris_denemesi(anahtar, zaman_utc);
CREATE INDEX giris_zaman ON alig.giris_denemesi(zaman_utc);

-- talep_id iletisim formu kaydinin kimligidir (contact.id). Yabanci anahtar KONMADI: eski SQLite'ta iki ayri dosya
-- oldugundan yetim satir olabilir; karar ALIG-DB-004 Faz C provasina birakildi (db/README.md).
CREATE TABLE alig.talep_durum(
  talep_id       bigint PRIMARY KEY,
  durum          text NOT NULL CHECK (durum IN ('yeni', 'gorusuluyor', 'kapandi')),
  aciklama       text NOT NULL DEFAULT '',
  guncelleme_utc timestamptz NOT NULL,
  guncelleyen    text NOT NULL
);

-- Giris yapilan IP'ler (duz adres yok, ozet).
CREATE TABLE alig.giris_ip(
  ad       text NOT NULL REFERENCES alig.kullanici(ad) ON DELETE CASCADE,
  ip_ozeti text NOT NULL,
  ilk_utc  timestamptz NOT NULL,
  son_utc  timestamptz NOT NULL,
  PRIMARY KEY (ad, ip_ozeti)
);

-- Yonetim denetim zinciri: tarama zinciriyle ayni bicim (yonetim/depo.py zincir.denetim_ekle).
CREATE TABLE alig.yonetim_denetim(
  seq       bigint PRIMARY KEY CHECK (seq >= 1),
  zaman_utc timestamptz NOT NULL,
  aktor     text NOT NULL,
  olay      text NOT NULL,
  onceki    text NOT NULL UNIQUE CHECK (onceki = '' OR onceki ~ '^[0-9a-f]{64}$'),
  ozet      text NOT NULL CHECK (ozet ~ '^[0-9a-f]{64}$'),
  mod       smallint NOT NULL DEFAULT 0 CHECK (mod IN (0, 1, 2, 3)),
  alanlar   text NOT NULL DEFAULT '',
  CHECK (seq > 1 OR onceki = '')
);

-- Iletisim formu (form/server.py). ip_hash duz IP degil ozettir.
CREATE TABLE alig.contact(
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_utc timestamptz NOT NULL,
  name        text NOT NULL,
  company     text NOT NULL,
  email       text NOT NULL,
  db          text NOT NULL,
  message     text NOT NULL,
  ip_hash     text NOT NULL
);
CREATE INDEX contact_created ON alig.contact(created_utc);

RESET ROLE;
