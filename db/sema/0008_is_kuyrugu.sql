-- 0008: job queue for the direct connection (Mode B) scan (roadmap item 21, ortak/is_kuyrugu_pg.py).
-- The queue only ever holds a REFERENCE to a request (istek_id -> baglanti_istegi); there is no payload column at all, so
-- a customer's login secret cannot be put in it by construction. The few text columns are constrained to short identifiers
-- (no spaces), so an error message or a value cannot be stored in them either.
-- Claiming uses FOR UPDATE SKIP LOCKED; fairness between companies uses is_kuyrugu_sira (one row per company, least recently served first).
-- States: bekliyor (waiting) -> calisiyor (leased) -> tamam (done) | olu (dead letter); a failed or expired job goes back to bekliyor
-- with a back-off while attempts remain. kira_no is a fencing token: it grows at every claim and a completion must carry the current one.
SET ROLE alig_owner;

CREATE TABLE alig.is_kuyrugu(
  id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tur            text NOT NULL CHECK (tur ~ '^[a-z0-9_]{1,40}$'),
  firma_id       bigint NOT NULL REFERENCES alig.firma(id) ON DELETE CASCADE,
  istek_id       bigint NOT NULL REFERENCES alig.baglanti_istegi(id) ON DELETE CASCADE,
  -- Non-null: the job can only be run by the process instance that holds its in-memory inputs (a restart makes it a dead letter).
  sahip          text CHECK (sahip ~ '^[A-Za-z0-9_.-]{1,64}$'),
  durum          text NOT NULL DEFAULT 'bekliyor' CHECK (durum IN ('bekliyor', 'calisiyor', 'tamam', 'olu')),
  deneme         integer NOT NULL DEFAULT 0 CHECK (deneme >= 0),
  azami_deneme   integer NOT NULL DEFAULT 5 CHECK (azami_deneme BETWEEN 1 AND 20),
  uygun_utc      timestamptz NOT NULL,
  isci           text CHECK (isci ~ '^[A-Za-z0-9_.-]{1,64}$'),
  kira_no        bigint NOT NULL DEFAULT 0 CHECK (kira_no >= 0),
  kira_bitis_utc timestamptz,
  olusturma_utc  timestamptz NOT NULL,
  alma_utc       timestamptz,
  bitis_utc      timestamptz,
  son_hata       text NOT NULL DEFAULT '' CHECK (son_hata ~ '^[a-z0-9_]{0,40}$'),
  UNIQUE (tur, istek_id),
  CHECK (durum <> 'calisiyor' OR (isci IS NOT NULL AND kira_bitis_utc IS NOT NULL)),
  CHECK (durum NOT IN ('tamam', 'olu') OR bitis_utc IS NOT NULL),
  CHECK (deneme <= azami_deneme)
);
CREATE INDEX is_kuyrugu_bekleyen ON alig.is_kuyrugu(firma_id, uygun_utc, id) WHERE durum = 'bekliyor';
CREATE INDEX is_kuyrugu_kira ON alig.is_kuyrugu(kira_bitis_utc) WHERE durum = 'calisiyor';
CREATE INDEX is_kuyrugu_calisan ON alig.is_kuyrugu(firma_id) WHERE durum = 'calisiyor';

-- Fairness state: the company whose turn came longest ago is served first; the row lock also serialises claims of one company.
CREATE TABLE alig.is_kuyrugu_sira(
  firma_id       bigint PRIMARY KEY REFERENCES alig.firma(id) ON DELETE CASCADE,
  son_hizmet_utc timestamptz
);

REVOKE ALL ON alig.is_kuyrugu, alig.is_kuyrugu_sira FROM PUBLIC;
-- The application role: no DELETE (finished rows go away with their request through the cascade) and no TRUNCATE.
GRANT SELECT, INSERT, UPDATE ON alig.is_kuyrugu, alig.is_kuyrugu_sira TO alig_app;
-- Read-only: states and counters for monitoring; not the owner process names.
GRANT SELECT (id, tur, firma_id, durum, deneme, azami_deneme, uygun_utc, olusturma_utc, bitis_utc, son_hata) ON alig.is_kuyrugu TO alig_readonly;

RESET ROLE;
